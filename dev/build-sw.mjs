// Writes sw-precache.js and src/version.js: every file the app needs offline, and a version hash of their contents.
//   node dev/build-sw.mjs           write them
//   node dev/build-sw.mjs --check   fail if they are stale
import { createHash } from "node:crypto";
import { existsSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const VERSION_FILE = "src/version.js";
const inDir = (dir, test) => readdirSync(join(root, dir)).filter(test).sort().map((name) => `${dir}/${name}`);

export function precacheList() {
  return [
    "index.html",
    "manifest.webmanifest",
    ...inDir("icons", (name) => name.endsWith(".png")),
    ...inDir("src", (name) => (name.endsWith(".js") || name.endsWith(".ttf")) && `src/${name}` !== VERSION_FILE),
    VERSION_FILE,
  ];
}

export function precacheVersion(files) {
  const hash = createHash("sha256");
  for (const file of [...files.filter((name) => name !== VERSION_FILE), "sw.js"]) hash.update(file).update(readFileSync(join(root, file)));
  return hash.digest("hex").slice(0, 16);
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const files = precacheList();
  const version = precacheVersion(files);
  const generated = {
    "sw-precache.js": `// Generated by dev/build-sw.mjs. Do not edit.\nself.MPOD_PRECACHE = ${JSON.stringify({ version, files }, null, 2)};\n`,
    [VERSION_FILE]: `// Generated by dev/build-sw.mjs. Do not edit.\nexport const VERSION = "${version.slice(0, 8)}";\n`,
  };
  if (process.argv.includes("--check")) {
    const stale = Object.keys(generated).filter((file) => !existsSync(join(root, file)) || readFileSync(join(root, file), "utf8") !== generated[file]);
    if (stale.length) {
      console.error(`stale: ${stale.join(", ")}. Run node dev/build-sw.mjs`);
      process.exit(1);
    }
  } else {
    for (const [file, text] of Object.entries(generated)) writeFileSync(join(root, file), text);
  }
  console.log(`${files.length} files, version ${version}`);
}
